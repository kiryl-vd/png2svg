"""Regression tests for complete release checksums and manifest transfer."""

import hashlib
import json
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

from check_release_checksums import read_checksums, verify_checksums


ARCHIVES = {
    "png2svg-aarch64-apple-darwin.tar.xz": b"macOS archive fixture",
    "png2svg-x86_64-unknown-linux-gnu.tar.xz": b"Linux archive fixture",
    "png2svg-x86_64-pc-windows-msvc.zip": b"Windows archive fixture",
    "source.tar.gz": b"source archive fixture",
}
PLAN = {"artifacts": {
    name: {"kind": "source-tarball" if name == "source.tar.gz" else "executable-zip"}
    for name in ARCHIVES
}}


class ChecksumTests(unittest.TestCase):
    """Require correct entries for all planned archives, not only source."""

    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.entries = {
            name: hashlib.sha256(content).hexdigest() for name, content in ARCHIVES.items()
        }
        for name, content in ARCHIVES.items():
            (self.root / name).write_bytes(content)
        self.write_list(self.entries)

    def write_list(self, entries):
        """Write checksum fixtures in the format generated by cargo-dist."""
        (self.root / "sha256.sum").write_text(
            "".join(f"{digest} *{name}\n" for name, digest in entries.items()), encoding="utf-8"
        )

    def test_complete_list_passes(self):
        self.assertEqual(verify_checksums(PLAN, self.root), 4)

    def test_source_only_list_reproduces_the_release_bug(self):
        self.write_list({"source.tar.gz": self.entries["source.tar.gz"]})
        with self.assertRaisesRegex(ValueError, "Incomplete checksum list"):
            verify_checksums(PLAN, self.root)

    def test_missing_archive_entry_is_rejected(self):
        entries = dict(self.entries)
        del entries["png2svg-x86_64-pc-windows-msvc.zip"]
        self.write_list(entries)
        with self.assertRaises(ValueError):
            verify_checksums(PLAN, self.root)

    def test_unexpected_entry_is_rejected(self):
        self.write_list(dict(self.entries, unexpected="0" * 64))
        with self.assertRaises(ValueError):
            verify_checksums(PLAN, self.root)

    def test_changed_archive_is_rejected(self):
        (self.root / "source.tar.gz").write_bytes(b"changed source")
        with self.assertRaisesRegex(ValueError, "SHA-256 mismatch"):
            verify_checksums(PLAN, self.root)

    def test_missing_archive_file_is_rejected(self):
        (self.root / "source.tar.gz").unlink()
        with self.assertRaises(OSError):
            verify_checksums(PLAN, self.root)

    def test_duplicate_entry_is_rejected(self):
        path = self.root / "sha256.sum"
        path.write_text(path.read_text() + path.read_text().splitlines()[0] + "\n")
        with self.assertRaisesRegex(ValueError, "Duplicate checksum"):
            verify_checksums(PLAN, self.root)

    def test_malformed_digest_or_unsafe_name_is_rejected(self):
        for line in ["invalid *source.tar.gz", "0" * 64 + " *../source.tar.gz",
                     "0" * 64 + " *dir\\source.tar.gz"]:
            with self.subTest(line=line):
                (self.root / "sha256.sum").write_text(line)
                with self.assertRaises(ValueError):
                    read_checksums(self.root / "sha256.sum")

    def test_comments_blank_lines_and_text_mode_are_supported(self):
        path = self.root / "sha256.sum"
        path.write_text("# SHA-256\n\n" + path.read_text().replace(" *", "  "))
        self.assertEqual(verify_checksums(PLAN, self.root), 4)

    def test_plan_without_archives_is_rejected(self):
        with self.assertRaises(ValueError):
            verify_checksums({"artifacts": {}}, self.root)

    def test_cli_fails_for_source_only_list(self):
        self.write_list({"source.tar.gz": self.entries["source.tar.gz"]})
        plan_path = self.root / "plan.json"
        plan_path.write_text(json.dumps(PLAN))
        script = Path(__file__).with_name("check_release_checksums.py")
        result = subprocess.run([sys.executable, str(script), str(plan_path), str(self.root)],
                                capture_output=True, text=True, check=False)
        self.assertEqual(result.returncode, 1)
        self.assertIn("Incomplete checksum list", result.stderr)

    def test_cli_passes_for_complete_list(self):
        plan_path = self.root / "plan.json"
        plan_path.write_text(json.dumps(PLAN))
        script = Path(__file__).with_name("check_release_checksums.py")
        result = subprocess.run([sys.executable, str(script), str(plan_path), str(self.root)],
                                capture_output=True, text=True, check=False)
        self.assertEqual(result.returncode, 0)
        self.assertIn("all 4 release archives", result.stdout)


class ManifestTransferTests(unittest.TestCase):
    """Keep platform manifests internal but available to the packaging job."""

    def test_workflow_transfers_manifests_and_checks_summary(self):
        path = Path(__file__).resolve().parents[1] / ".github/workflows/publish-release.yml"
        text = path.read_text(encoding="utf-8")
        build = text.split("  build:\n", 1)[1].split("  package:\n", 1)[0]
        package = text.split("  package:\n", 1)[1].split("  publish:\n", 1)[0]
        self.assertIn("BUILD_MANIFEST_NAME: target/distrib/${{ matrix.host }}-dist-manifest.json", build)
        self.assertIn('cp local-dist-manifest.json "$BUILD_MANIFEST_NAME"', build)
        self.assertIn("target/distrib/*-dist-manifest.json", build)
        self.assertIn("pattern: binaries-*", package)
        self.assertIn("python3 tools/check_release_checksums.py release-plan.json target/distrib", package)
        # Internal manifests must not become public release assets.
        published_paths = package.split("name: release-assets", 1)[1]
        self.assertNotIn("*-dist-manifest.json", published_paths)


if __name__ == "__main__":
    unittest.main()
